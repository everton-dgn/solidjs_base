import assert from 'node:assert/strict'
import { mkdtemp, readFile, realpath, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { describe, it, type TestContext } from 'node:test'

import {
  checkIconTypes,
  type IconTypesOptions,
  writeIconTypes
} from '../index.ts'

type Workspace = { icons: string; typesFile: string }

// The package declares @iconify-json/hugeicons in its package.json.
const PACKAGE_ROOT = path.resolve(import.meta.dirname, '../../..')
const SVG = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"/>'

async function workspace(context: TestContext): Promise<Workspace> {
  const prefix = path.join(tmpdir(), 'solid-icons-types-')
  const folder = await realpath(await mkdtemp(prefix))
  context.after(() => rm(folder, { recursive: true, force: true }))
  await writeFile(path.join(folder, 'star.svg'), SVG)
  await writeFile(path.join(folder, 'dot-01.svg'), SVG)
  await writeFile(path.join(folder, 'dot01.svg'), SVG)
  return {
    icons: folder,
    typesFile: path.join(folder, 'types/icon-collections.d.ts')
  }
}

function typesOptions({ icons, typesFile }: Workspace): IconTypesOptions {
  return { root: PACKAGE_ROOT, collections: { own: icons }, typesFile }
}

describe('writeIconTypes', () => {
  it('declares a module per collection with an export per icon', async context => {
    const files = await workspace(context)
    const { file, isChanged } = await writeIconTypes(typesOptions(files))
    const types = await readFile(file, 'utf8')

    assert.equal(file, files.typesFile)
    assert.equal(isChanged, true)
    assert.match(
      types,
      /^\/\/ Generated by @evertondgn\/vite-plugin-solid-icons/u
    )
    assert.ok(types.indexOf("declare module 'icon:hugeicons' {") > 0)
    assert.ok(
      types.indexOf("declare module 'icon:hugeicons' {") <
        types.indexOf("declare module 'icon:own' {"),
      'the modules follow the order of the names'
    )
    assert.match(
      types,
      / {2}import type \{ IconComponent \} from '@evertondgn\/vite-plugin-solid-icons\/types'\n/u
    )
    assert.match(
      types,
      / {2}\/\*\* icon:hugeicons\/arrow-left-01 \*\/\n {2}export const ArrowLeft01: IconComponent\n/u
    )
    assert.match(
      types,
      / {2}\/\*\* icon:hugeicons\/1st-bracket \*\/\n {2}export const FirstBracket: IconComponent\n/u
    )
    assert.match(types, /export const ArrowDown_01: IconComponent/u)
    assert.doesNotMatch(types, /export const ArrowDown01:/u)
    assert.match(
      types,
      / {2}\/\*\* icon:own\/dot-01 \*\/\n {2}export const Dot_01: IconComponent\n/u
    )
    assert.match(types, /export const Star: IconComponent/u)
    assert.doesNotMatch(types, /export \{\}/u)
    assert.ok(types.endsWith('}\n'))
  })

  it('keeps the file when the icons are the same', async context => {
    const files = await workspace(context)
    await writeIconTypes(typesOptions(files))

    const { isChanged } = await writeIconTypes(typesOptions(files))

    assert.equal(isChanged, false)
  })
})

describe('checkIconTypes', () => {
  it('accepts the file that writeIconTypes wrote', async context => {
    const files = await workspace(context)
    await writeIconTypes(typesOptions(files))

    await checkIconTypes(typesOptions(files))
  })

  it('fails on a missing file and on a file behind the icons', async context => {
    const files = await workspace(context)
    const outOfDate = {
      message: `${path.relative(PACKAGE_ROOT, files.typesFile)} is out of date with the icon collections: write it again with writeIconTypes, the dev server or the build.`
    }

    await assert.rejects(checkIconTypes(typesOptions(files)), outOfDate)
    await writeIconTypes(typesOptions(files))
    await writeFile(path.join(files.icons, 'moon.svg'), SVG)
    await assert.rejects(checkIconTypes(typesOptions(files)), outOfDate)
  })
})
