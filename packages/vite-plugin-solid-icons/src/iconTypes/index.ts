import { randomUUID } from 'node:crypto'
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { pid } from 'node:process'

import { errorCode, messageOf } from '../errorText/index.ts'
import {
  declaredCollections,
  type Folders,
  type NameTables
} from '../iconCollections/index.ts'
import { iconImport, isCollectionName } from '../iconIds/index.ts'
import type { NameTable } from '../iconNames/index.ts'

type ModuleInput = { collection: string; table: NameTable }

const PACKAGE_NAME = '@evertondgn/vite-plugin-solid-icons'
const HEADER = `// Generated by ${PACKAGE_NAME} from the icon collections
// of the application. The dev server and the build write it again.
`

function compare(first: string, second: string): number {
  if (first === second) return 0
  return first < second ? -1 : 1
}

function moduleDeclaration({ collection, table }: ModuleInput): string {
  const exports = [...table.exports].toSorted(([first], [second]) =>
    compare(first, second)
  )
  return [
    `declare module 'icon:${collection}' {`,
    `  import type { IconComponent } from '${PACKAGE_NAME}/types'`,
    '',
    ...exports.flatMap(([name, icon]) => [
      `  /** ${iconImport({ collection, name: icon })} */`,
      `  export const ${name}: IconComponent`
    ]),
    '}',
    ''
  ].join('\n')
}

export type TypesSource = { root: string; folders: Folders; tables: NameTables }

export type TypesFileContent = { file: string; content: string }

export type RenderedTypes = {
  content: string
  // The collections left out, with the reason.
  warnings: string[]
}

// WHY: a tsconfig that includes src, as most applications have, reads the
// file without another entry.
export const DEFAULT_TYPES_FILE = 'src/icon-collections.d.ts'

// One module per collection that the package.json of the application
// installs and per folder collection, in a fixed order, so the file only
// changes with the icons. A collection that cannot be read is left out with
// a warning, so the others keep their names.
export async function renderIconTypes({
  root,
  folders,
  tables
}: TypesSource): Promise<RenderedTypes> {
  const installed = await declaredCollections(root)
  const collections = [...new Set([...installed, ...folders.keys()])]
    .filter(collection => isCollectionName(collection))
    .toSorted(compare)
  const results = await Promise.allSettled(
    collections.map(async collection =>
      moduleDeclaration({ collection, table: await tables.get(collection) })
    )
  )
  const modules: string[] = []
  const warnings: string[] = []
  for (const [index, result] of results.entries()) {
    if (result.status === 'fulfilled') {
      modules.push(result.value)
      continue
    }
    warnings.push(
      `The icon declarations leave out the collection "${collections[index]}": ${messageOf(result.reason)}`
    )
  }
  return { content: [HEADER, ...modules].join('\n'), warnings }
}

export async function readTypesFile(file: string): Promise<string | undefined> {
  try {
    return await readFile(file, 'utf8')
  } catch {
    return undefined
  }
}

// An unchanged file keeps its time, so the editor and the watchers do not
// read it again. A new content replaces the file in one rename, so a dev
// server, a build or a type check that reads it at the same time sees the
// old or the new file, never a part of one.
export async function writeTypesFile({
  file,
  content
}: TypesFileContent): Promise<boolean> {
  if ((await readTypesFile(file)) === content) return false
  const folder = path.dirname(file)
  const temporary = path.join(
    folder,
    `.${path.basename(file)}.${pid}-${randomUUID()}.tmp`
  )
  try {
    await mkdir(folder, { recursive: true })
    await writeFile(temporary, content)
    await rename(temporary, file)
  } catch (error) {
    await rm(temporary, { force: true })
    throw new Error(
      `The icon declarations cannot be written to ${file} (${errorCode(error)}).`,
      { cause: error }
    )
  }
  return true
}
